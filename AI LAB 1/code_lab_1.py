"""Task 2:"""
MIN_SCORE = 70
MIN_GPA = 2.5
MAX_INCOME = 50000

def rule_check(score, complete, gpa, income):
    failed = []
    if not complete:
        failed.append("documents_incomplete")
    if score < MIN_SCORE:
        failed.append(f"score<{MIN_SCORE}")
    if gpa < MIN_GPA:
        failed.append(f"minimum_gpa<{MIN_GPA}")
    if income > MAX_INCOME:
        failed.append(f"income_over_limit>{MAX_INCOME}")
    if failed:
        return "Hold", "failed: " + ", ".join(failed)
    return "Review", "all conditions satisfied"
tests = [
    ("T1_pass",82, True, 3.4, 35000, "Review", "all conditions clearly met"),
    ("T2_fail_min_gpa",80, True, 2.1, 30000, "Hold","only new condition 1 fal"),
    ("T3_fail_income",85, True, 3.2, 72000, "Hold","only new condition 2 fail"),
    ("T4_boundary",70, True, 2.5, 50000, "Review","every threshold exactly  limit (>= / <=)"),]
print("SYNTHETIC thresholds: score>=70, documents complete, gpa>=2.5, income<=50000\n")
passed = 0
for name, score, complete, gpa, income, expected, why in tests:
    actual, reason = rule_check(score, complete, gpa, income)
    ok = actual == expected
    passed += ok
    print(f"{name}")
    print(f"  input    : score={score}, complete={complete}, gpa={gpa}, income={income}")
    print(f"  expected : {expected}")
    print(f"  actual   : {actual}   ({'MATCH' if ok else 'MISMATCH'})")
    print(f"  reason   : {reason}")
    print(f"  why chosen: {why}\n")
print(f"{passed}/{len(tests)} core tests matched expectation")
print("\nEdge case: high score, incomplete documents")
print(rule_check(91, False, 3.8, 20000))



