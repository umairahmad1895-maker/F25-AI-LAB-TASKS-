graph = {"A": ["B", "C"],  "B": ["D", "E"],"C": ["F"],"D": [],"E": ["G"],"F": [],"G": []}
def dls(node, goal, limit, path):
    if node == goal:
        return "FOUND", path
    if limit == 0:
        if graph[node]:
            return "CUTOFF", None
        return "FAILURE", None
    cutoff = False
    for child in graph[node]:
        if child in path:
            continue
        status, result = dls(
            child, goal, limit - 1,
            path + [child] )
        if status == "FOUND":
            return status, result
        if status == "CUTOFF":
            cutoff = True
    if cutoff:
        return "CUTOFF", None
    return "FAILURE", None
def iddfs(start, goal, max_depth):
    for limit in range(max_depth + 1):
        status, path = dls(
            start, goal, limit, [start])

        print("Limit:", limit,
              "Status:", status, "Path:", path)
        if status == "FOUND":
            return path
    return None
for limit in [1, 2, 3, 4]:
    print("DLS limit", limit, ":",
          dls("A", "G", limit, ["A"]))
print("IDDFS results:")
iddfs("A", "G", 4)

