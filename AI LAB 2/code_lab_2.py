class ClassroomAgent:
    def __init__(self):
        self.previous_mode = None
    def act(self, temp, occupied):
        if not occupied:
            target_mode = "ECO"
        elif temp > 26:
            target_mode = "COOL"
        elif temp < 20:
            target_mode = "WARM"
        else:
            target_mode = "IDLE"
        send_command = (target_mode != self.previous_mode)
        old_mode = self.previous_mode
        self.previous_mode = target_mode
        return old_mode, target_mode, send_command
agent = ClassroomAgent()
percepts = [(29, True),(29, True),(20, True),(26, True),(19, True),(29, False),(29, False)]
print("Step | Previous mode | Percept | Target mode | Outcome")
for step, percept in enumerate(percepts, 1):
    old_mode, target, send = agent.act(*percept)
    outcome = "SEND COMMAND" if send else "NO COMMAND"
    print(f"{step:>4} | {str(old_mode):<13} | {str(percept):<12} | {target:<11} | {outcome}")