import heapq
GRAPH = {
    "S": [("A", 1), ("B", 4)],"A": [("C", 2)],"B": [("G", 5)],"C": [("G", 3)],"G": [],}
HEURISTIC = {"S": 5, "A": 4, "B": 4, "C": 2, "G": 0}
START, GOAL = "S", "G"
def search(graph, heuristic, start=START, goal=GOAL, label="A*"):
    pq = [(heuristic[start], 0, start, [start])]
    best = {start: 0}
    processed = []
    expanded = []
    while pq:
        f, g, node, path = heapq.heappop(pq)
        if g != best.get(node):
            print(f"Skip stale entry: node={node}, g={g}, f={f}")
            continue
        processed.append(node)
        print(f"Process {node}: g={g}, h={heuristic[node]}, f={f}, path={' -> '.join(path)}")
        if node == goal:
            cost = sum(next(w for nxt, w in graph[u] if nxt == v)for u, v in zip(path, path[1:]))
            print(f"Goal reached. Path={' -> '.join(path)}, returned cost={g}, independently cost={cost}")
            print(f"Procesed trace: {processed}")
            print(f"Expanded nodes: {expanded}")
            print(f"Expansion count: {len(expanded)}")
            return {
                "path": path, "cost": g, "independe_cost": cost,
                "processed": processed, "expanded": expanded,
                "expansion_count": len(expanded) }
        expanded.append(node)
        for nxt, weight in graph.get(node, []):
            new_g = g + weight
            if new_g < best.get(nxt, float("inf")):
                best[nxt] = new_g
                new_f = new_g + heuristic[nxt]
                heapq.heappush(pq, (new_f, new_g, nxt, path + [nxt]))
                print(f"update {nxt}: g={new_g}, h={heuristic[nxt]}, f={new_f}")
    print("No path found.")
    return None
def main():
    astar_result = search(GRAPH, HEURISTIC, label="A* with supplied heuristic")
    zero_h = {node: 0 for node in GRAPH}
    ucs_result = search(GRAPH, zero_h, label="UCS control (h=0)")
    bad_h = dict(HEURISTIC)
    bad_h["C"] = 10
    overestimate_result = search(GRAPH, bad_h, label="A* overestimate experiment (h(C)=10)")
    print("\n--- Summary ---")
    for name, result in [
        ("A*", astar_result), ("UCS", ucs_result),
        ("A* with h(C)=10", overestimate_result) ]:
        print(f"{name}: path={' -> '.join(result['path'])}, cost={result['cost']}, "
              f"processed={result['processed']}, expanded={result['expanded']}, "
              f"expansion_count={result['expansion_count']}")
if __name__ == "__main__":
    main()