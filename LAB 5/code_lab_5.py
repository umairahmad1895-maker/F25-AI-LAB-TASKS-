def minimax(depth, index, max_turn, scores, target, count):
  if depth == target:
     count[0] += 1
     return scores[index]
  left = minimax(depth + 1, index * 2, not max_turn, scores, target, count)
  right = minimax(depth + 1, index * 2 + 1, not max_turn, scores, target, count)
  return max(left, right) if max_turn else min(left, right)
def alphabeta(depth, index, max_turn, scores, target, alpha, beta, count):
  if depth == target:
    count[0] += 1
    return scores[index]
  if max_turn:
    value = float('-inf')
    for i in range(2):
      value = max(value, alphabeta(depth + 1, index * 2 + i, False, scores, target,  alpha, beta, count))
      alpha = max(alpha, value)
      if alpha >= beta:
        break
    return value
  else:
    value = float('inf')
    for i in range(2):
      value = min(value, alphabeta(depth + 1, index * 2 + i, True, scores, target,alpha, beta, count))
      beta = min(beta, value)
      if alpha >= beta:
        break
    return value
